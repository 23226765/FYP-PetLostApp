import { mount, flushPromises, enableAutoUnmount } from '@vue/test-utils'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import PostPetScreen from '../PostPetScreen.vue'
import { getCurrentLocation } from '../../services/geolocation'
import { setSessionToken } from '../../services/authSession'
import { i18n } from '../../i18n'
const api = vi.hoisted(() => ({ reportLostPet: vi.fn(), uploadManagedImage: vi.fn(), discardManagedImage: vi.fn() }))
vi.mock('../../services/api', () => api)
vi.mock('../../services/geolocation', () => ({ getCurrentLocation: vi.fn() }))
vi.mock('leaflet', () => ({ default: {
  map: vi.fn(() => { throw new Error('Offline map fixture') }),
} }))
enableAutoUnmount(afterEach)
beforeEach(() => {
  vi.resetAllMocks()
  i18n.global.locale.value = 'en'
  setSessionToken('fictional-pet-test')
  vi.spyOn(URL, 'createObjectURL').mockReturnValue('blob:fictional-pet')
  api.discardManagedImage.mockResolvedValue(undefined)
  api.uploadManagedImage.mockResolvedValue({ id: 'd'.repeat(24) })
  api.reportLostPet.mockResolvedValue({})
})
afterEach(() => { vi.unstubAllGlobals(); i18n.global.locale.value = 'en' })
function render() {
  return mount(PostPetScreen, { props: { user: { id: 'owner-id', name: 'Owner', email: 'owner@example.test' } }, global: { stubs: { AppIcon: true, ManagedImage: true } } })
}
async function confirm(wrapper: ReturnType<typeof render>) {
  const fields = wrapper.findAll('.coordinate-fields input')
  await fields[0].setValue('22.41')
  await fields[1].setValue('114.21')
  await wrapper.get('.confirm-location').trigger('click')
}
async function selectPhoto(wrapper: ReturnType<typeof render>) {
  const input = wrapper.get('input[type="file"]')
  Object.defineProperty(input.element, 'files', { configurable: true, value: [new File(['raster'], 'pet.png', { type: 'image/png' })] })
  await input.trigger('change')
}

it.each(['en', 'zh-HK', 'zh-CN'] as const)('distinguishes the location description from map confirmation in %s', async locale => {
  i18n.global.locale.value = locale
  const wrapper = render()
  expect(wrapper.get('.input-icon').element.closest('label')?.textContent).toContain(i18n.global.t('reportLocation.descriptionLabel'))
  expect(wrapper.get('.input-icon input').attributes('placeholder')).toBe(i18n.global.t('pets.locationPlaceholder'))
  expect(wrapper.get('.location-heading h3').text()).toBe(i18n.global.t('reportLocation.mapTitle'))
  await confirm(wrapper)
  expect(wrapper.get('.location-summary strong').text()).toBe(i18n.global.t('sightings.confirmedPoint'))
  expect(vi.mocked(getCurrentLocation)).not.toHaveBeenCalled()
  expect(api.reportLostPet).not.toHaveBeenCalled()
})
it('pet report retries reuse uploaded IDs and submission identity with exactly the confirmed lng/lat', async () => {
  api.reportLostPet.mockReset().mockRejectedValueOnce(new Error('Network Error')).mockResolvedValueOnce({})
  const wrapper = render()
  await wrapper.get('input[type="text"]').setValue('Maple')
  await wrapper.get('.input-icon input').setValue('Last seen park')
  await confirm(wrapper); await selectPhoto(wrapper)
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(wrapper.find('.error-msg').exists()).toBe(true)
  expect((wrapper.get('input[type="text"]').element as HTMLInputElement).value).toBe('Maple')
  expect((wrapper.get('.input-icon input').element as HTMLInputElement).value).toBe('Last seen park')
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(api.uploadManagedImage).toHaveBeenCalledTimes(1)
  expect(api.uploadManagedImage.mock.calls[0][1]).toBe('pet')
  expect(api.reportLostPet.mock.calls[0][0]).toMatchObject({ imageIds: ['d'.repeat(24)], coordinates: [114.21, 22.41], locationName: 'Last seen park' })
  expect(api.reportLostPet.mock.calls[0][0]).not.toHaveProperty('photo')
  expect(api.reportLostPet.mock.calls[0][0].submissionId).toBe(api.reportLostPet.mock.calls[1][0].submissionId)
  expect(vi.mocked(getCurrentLocation)).not.toHaveBeenCalled()
  expect(wrapper.find('.success').exists()).toBe(true)
})
it.each(['en', 'zh-HK', 'zh-CN'] as const)('intentional cancellation preserves the draft and retry key without a false posting error in %s', async locale => {
  i18n.global.locale.value = locale
  api.uploadManagedImage.mockImplementationOnce((_file, _purpose, _key, options) => new Promise((_resolve, reject) => {
    options.signal.addEventListener('abort', () => reject(Object.assign(new Error('Transport cancelled'), { code: 'ERR_CANCELED' })))
  }))
  const wrapper = render()
  await wrapper.get('input[type="text"]').setValue('Maple cancellation fixture')
  await wrapper.get('.input-icon input').setValue('Preserved last-seen park')
  await confirm(wrapper); await selectPhoto(wrapper)
  await wrapper.get('form').trigger('submit')
  expect(wrapper.get('.submit').attributes('disabled')).toBeDefined()
  await wrapper.get('.upload-status button').trigger('click'); await flushPromises()
  expect(wrapper.find('.error-msg').exists()).toBe(false)
  expect(wrapper.get('.upload-status').text()).toContain(i18n.global.t('media.cancelled'))
  expect((wrapper.get('input[type="text"]').element as HTMLInputElement).value).toBe('Maple cancellation fixture')
  expect((wrapper.get('.input-icon input').element as HTMLInputElement).value).toBe('Preserved last-seen park')
  expect(wrapper.find('managed-image-stub').exists()).toBe(true)
  expect(wrapper.get('.confirm-location').attributes('disabled')).toBeDefined()
  expect(api.reportLostPet).not.toHaveBeenCalled()
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(api.uploadManagedImage).toHaveBeenCalledTimes(2)
  expect(api.uploadManagedImage.mock.calls[0][2]).toBe(api.uploadManagedImage.mock.calls[1][2])
  expect(api.reportLostPet).toHaveBeenCalledTimes(1)
  expect(api.reportLostPet.mock.calls[0][0]).toMatchObject({ name: 'Maple cancellation fixture', coordinates: [114.21, 22.41], imageIds: ['d'.repeat(24)] })
  expect(wrapper.find('.success').exists()).toBe(true)
})
it.each(['IMAGE_STORAGE_UNAVAILABLE', 'NETWORK_UNAVAILABLE', 'ERR_CANCELED'])('genuine failure %s is not suppressed without intentional abort', async code => {
  api.uploadManagedImage.mockRejectedValueOnce(Object.assign(new Error('Synthetic failure'), { apiCode: code }))
  const wrapper = render()
  await confirm(wrapper); await selectPhoto(wrapper)
  await wrapper.get('form').trigger('submit'); await flushPromises()
  expect(wrapper.get('.error-msg').text()).not.toBe('')
  expect(wrapper.get('.upload-status').text()).not.toContain(i18n.global.t('media.cancelled'))
  expect(api.reportLostPet).not.toHaveBeenCalled()
})
it.each(['success', 'failure'] as const)('a still-mounted form ignores obsolete upload %s after a cross-tab account change', async outcome => {
  let finish!: (value: { id: string }) => void, fail!: (error: Error) => void
  api.uploadManagedImage.mockImplementationOnce(() => new Promise((resolve, reject) => { finish = resolve; fail = reject }))
  const wrapper = render()
  await wrapper.get('input[type="text"]').setValue('Old account draft')
  await confirm(wrapper); await selectPhoto(wrapper)
  await wrapper.get('form').trigger('submit')
  const formElement = wrapper.get('form').element
  localStorage.setItem('token', 'replacement-cross-tab-fixture')
  window.dispatchEvent(new StorageEvent('storage', { key: 'token', oldValue: 'fictional-pet-test', newValue: 'replacement-cross-tab-fixture', storageArea: localStorage }))
  await flushPromises()
  if (outcome === 'success') finish({ id: 'c'.repeat(24) })
  else fail(Object.assign(new Error('Late provider outage'), { apiCode: 'IMAGE_STORAGE_UNAVAILABLE' }))
  await flushPromises()
  expect(wrapper.get('form').element).toBe(formElement)
  expect((wrapper.get('input[type="text"]').element as HTMLInputElement).value).toBe('')
  expect(wrapper.find('managed-image-stub').exists()).toBe(false)
  expect(wrapper.find('.error-msg').exists()).toBe(false)
  expect(wrapper.find('.success').exists()).toBe(false)
  expect(api.reportLostPet).not.toHaveBeenCalled()
  expect(api.discardManagedImage).not.toHaveBeenCalled()
})
