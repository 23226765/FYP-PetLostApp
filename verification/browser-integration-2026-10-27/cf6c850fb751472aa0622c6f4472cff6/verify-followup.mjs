// Read-only checks over exact run ledgers; never connects to a database/provider.
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const json = async url => JSON.parse(await readFile(url, 'utf8'))
const old = await json(new URL('../../browser-integration-2026-10-26/0eb769b6fbbc4443aa906aef5ce27f41/ledger.json', import.meta.url))
const recovery = await json(new URL('../../browser-integration-2026-10-26/0eb769b6fbbc4443aa906aef5ce27f41/recovery.json', import.meta.url))
assert.equal(recovery.cleanupComplete, true)
assert.equal(recovery.emptyCollectionsVerified, true)
assert.equal(recovery.records.users.length, 3)
assert.equal(recovery.records.pets.length, 1)
assert.equal(recovery.records.mediaassets.length, 4)
const pet = recovery.final.pets[0]
assert.equal(pet.name, 'Cancel Fixed Fixture')
assert.equal(pet.imageIds.length, 1)
const attached = recovery.final.assets.find(a => a._id === pet.imageIds[0])
assert.equal(attached.state, 'attached')
assert.equal(attached.attachedTo.id, pet._id)
assert.equal(old.providerEvents.filter(e => e.assetId === attached._id && e.event === 'upload-start').length, 1)
assert.ok(old.requests.some(r => r.path === '/api/uploads/managed' && r.status === 200 && r.imageKey === attached.idempotencyKey))
assert.equal(old.requests.filter(r => r.path === '/api/pets/report').length, 1)
assert.equal(recovery.final.assets.filter(a => a.state === 'pending' && !a.attachedTo).length, 2)
assert.equal(recovery.final.assets.filter(a => a.state === 'deleted' && a.failureCode === 'IMAGE_STORAGE_UNAVAILABLE').length, 1)
const current = await json(new URL('./ledger.json', import.meta.url))
assert.equal(current.database, 'fyp_transactions_browser_cf6c850fb751472aa0622c6f4472cff6')
const last = current.snapshots.at(-1)
assert.equal(last.pets.length, 0)
assert.ok(last.users.every(u => u.avatar === ''))
assert.equal(last.assets.length, 1)
assert.equal(last.assets[0].state, 'deleted')
assert.equal(last.assets[0].failureCode, 'IMAGE_STORAGE_UNAVAILABLE')
assert.ok(!last.assets[0].attachedTo)
const owner = last.users.find(u => u.name === 'Browser owner')
assert.equal(last.assets[0].uploadedBy, owner._id)
assert.equal(current.requests.filter(r => r.path === '/api/pets/report').length, 0)
const start = current.providerEvents.find(e => e.event === 'upload-start')
const failure = current.providerEvents.find(e => e.event === 'upload-failed')
const login = current.requests.filter(r => r.path === '/api/auth/login' && r.status === 200).at(-1)
assert.equal(start.assetId, failure.assetId)
assert.ok(new Date(start.at) < new Date(login.finishedAt))
assert.ok(new Date(login.finishedAt) < new Date(failure.at))
assert.equal(current.objects.length, 0)
assert.equal(current.cleanupComplete, true)
assert.equal(current.records.users.length, 3)
assert.equal(current.records.mediaassets.length, 1)
assert.equal(current.records.mediauploadbudgets.length, 1)
console.log('PASS: cancellation retry identity; no duplicate/obsolete content; old fixture recovery; delayed failure after replacement login; uploader attribution and compensation; final exact cleanup.')
