// Read-only assertions over this exact browser run's recorded evidence.
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const ledger = JSON.parse(await readFile(new URL('./ledger.json', import.meta.url), 'utf8'))
assert.equal(ledger.database, 'fyp_transactions_browser_73ce3fb9e2f84728beac5d9e1de6bfd5')
assert.equal(ledger.provider, 'in-memory mock')
const snapshots = ledger.snapshots
const final = snapshots.at(-1)
const cancelAsset = final.assets.find(asset => asset._id === '6adf2e1ea744fbde2b518c4c')
assert.ok(snapshots.some(s => s.pets.length === 0 && s.assets.some(a => a._id === cancelAsset._id && a.state === 'uploading' && !a.attachedTo)))
assert.ok(snapshots.some(s => s.pets.length === 0 && s.assets.some(a => a._id === cancelAsset._id && a.state === 'pending' && !a.attachedTo) && s.mockObjects.length === 1))
assert.equal(ledger.providerEvents.filter(e => e.event === 'upload-start' && e.assetId === cancelAsset._id).length, 1)
assert.ok(ledger.requests.some(r => r.path === '/api/uploads/managed' && r.status === 200 && r.imageKey === cancelAsset.idempotencyKey))
assert.equal(cancelAsset.state, 'attached')
assert.deepEqual(final.pets.map(p => p.name).sort(), ['Active Cancel Fixture', 'Provider Retry Fixture'])
assert.equal(new Set(final.pets.map(p => p.submissionId)).size, 2)
assert.ok(final.pets.every(p => p.submissionId && p.imageIds.length === 1))
assert.equal(new Set(final.pets.flatMap(p => p.imageIds)).size, 2)
for (const pet of final.pets) {
  const asset = final.assets.find(a => a._id === pet.imageIds[0])
  assert.equal(asset.state, 'attached'); assert.equal(asset.attachedTo.id, pet._id)
}
const failed = final.assets.find(a => a.failureCode === 'IMAGE_STORAGE_UNAVAILABLE')
assert.equal(failed.state, 'deleted'); assert.ok(!failed.attachedTo)
assert.ok(ledger.requests.some(r => r.path === '/api/uploads/managed' && r.status === 503 && r.imageKey === failed.idempotencyKey))
const retry = final.assets.find(a => a._id === final.pets.find(p => p.name === 'Provider Retry Fixture').imageIds[0])
assert.notEqual(retry.idempotencyKey, failed.idempotencyKey) // terminal failure deliberately needs a fresh reservation
assert.equal(ledger.requests.filter(r => r.path === '/api/pets/report').length, 2)
assert.ok(ledger.requests.filter(r => r.path === '/api/pets/report').every(r => r.status === 201))
const reporter = final.users.find(u => u.name === 'Browser reporter')
assert.equal(reporter.avatar, '')
assert.equal(final.pets.filter(p => p.reportedBy === reporter._id).length, 0)
const pending = final.assets.filter(a => a.state === 'pending')
assert.equal(pending.length, 2)
assert.ok(pending.every(a => !a.attachedTo && a.uploadedBy !== reporter._id && new Date(a.expiresAt) > new Date(final.at)))
const late = ledger.providerEvents.filter(e => e.event === 'upload-finished').at(-1)
const started = ledger.providerEvents.find(e => e.event === 'upload-start' && e.assetId === late.assetId)
const login = ledger.requests.filter(r => r.path === '/api/auth/login' && r.status === 200).at(-1)
assert.ok(new Date(started.at) < new Date(login.finishedAt))
assert.ok(new Date(login.finishedAt) < new Date(late.at))
assert.equal(ledger.cleanupComplete, true)
assert.equal(ledger.records.users.length, 3)
assert.equal(ledger.records.pets.length, 2)
assert.equal(ledger.records.mediaassets.length, 5)
assert.equal(ledger.objects.length, 4)
assert.ok(ledger.objects.every(o => o.absentConfirmed === true))
console.log('PASS: cancelled-upload identity reuse; no unintended/duplicate content or attachments; terminal-failure recovery; late completion after replacement login; exact fixture/mock-object cleanup.')
